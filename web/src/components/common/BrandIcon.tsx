export interface BrandBadgeProps {
  name: BrandName;
  size?: number; // dimension in pixels, e.g. 34 for engine list
  className?: string;
  rounded?: string;
}

/**
 * BrandBadge renders the brand logo in an official styled container.
 * Drop-in replacement for the previous letter boxes like <div className="engine-logo chatgpt">C</div>.
 */
export const BrandBadge: React.FC<BrandBadgeProps> = ({
  name,
  size = 34,
  className = '',
  rounded = 'rounded-[9px]',
}) => {
  const meta = getBrandMeta(name);
  const iconSize = Math.round(size * 0.60);

  return (
    <div
      className={`inline-flex shrink-0 items-center justify-center shadow-2xs select-none ${rounded} ${className}`}
      style={{
        width: size,
        height: size,
        backgroundColor: meta.bgColor,
      }}
      title={meta.displayName}
    >
      <BrandIcon name={meta.key} size={iconSize} color="#ffffff" />
    </div>
  );
};
